import {
	AbsoluteFill,
	interpolate,
	spring,
	useCurrentFrame,
	useVideoConfig,
} from 'remotion';

export const Triangle = ({delay}: {delay: number}) => {
	const {fps} = useVideoConfig();
	const frame = useCurrentFrame();
	const entrance = spring({
		fps,
		frame: frame - delay,
		config: {
			damping: 20,
		},
	});

	const push = spring({
		fps,
		frame: frame - 50 - delay,
		config: {
			mass: 0.7,
			damping: 200,
		},
	});

	const scale = interpolate(entrance, [0, 1], [0, 2]) + push * 17;
	const rotate =
		interpolate(entrance, [0, 1], [-Math.PI * 2, 0]) +
		interpolate(frame - delay, [0, 30, 60], [-0.3, 0, 0.3]);

	return (
		<AbsoluteFill
			style={{
				justifyContent: 'center',
				alignItems: 'center',
				transform: `scale(${scale}) rotate(${rotate}rad)`,
			}}
		>
			<svg
				width="152"
				height="157"
				viewBox="0 0 152 157"
				fill="none"
				xmlns="http://www.w3.org/2000/svg"
			>
				<path
					d="M34.4265 0.100372C31.1409 0.278717 28.4932 0.800018 25.825 1.81519C24.4943 2.31592 22.3131 3.40654 21.1127 4.16106C16.0917 7.30945 12.2643 12.0423 10.2683 17.5503C9.87042 18.6409 8.79352 22.1185 8.10074 24.5124C3.48447 40.515 0.864244 58.0129 0.301787 76.5328C0.212617 79.4823 0.212617 86.5062 0.301787 89.4076C0.679045 101.686 1.85197 112.77 3.97834 124.074C4.8426 128.649 6.22817 134.795 7.0307 137.587C8.67005 143.259 12.0174 148.088 16.7777 151.628C19.9672 154.001 23.5889 155.592 27.6015 156.374C29.5358 156.752 32.0875 156.923 33.9669 156.8C36.5666 156.628 41.7247 155.935 45.9157 155.188C64.806 151.82 82.2559 145.791 98.0802 137.162C108.102 131.695 116.669 125.775 124.934 118.594C133.172 111.446 140.196 103.757 146.376 95.1282C147.81 93.1322 148.53 91.9661 149.25 90.4982C151.102 86.712 151.973 82.9462 151.966 78.7347C151.966 74.8112 151.226 71.3267 149.627 67.7599C148.859 66.0382 148.125 64.8036 146.479 62.4577C140.415 53.8219 133.686 46.2973 125.483 38.9854C112.766 27.6539 97.6618 18.3597 80.7949 11.4799C77.1389 9.99141 73.5378 8.68129 69.2028 7.26143C60.0251 4.26395 48.6663 1.66429 39.0565 0.367905C37.5474 0.162125 35.4965 0.0455017 34.4265 0.100372Z"
					fill="#0B84F3"
				/>
			</svg>
		</AbsoluteFill>
	);
};
